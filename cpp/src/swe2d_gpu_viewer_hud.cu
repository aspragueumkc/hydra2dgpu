__device__ const uint8_t* glyph_for(uint8_t c) {
    if (c < 32 || c > 127) c = 63;  // '?' fallback
    return d_font + (c - 32) * 7;
}

// One thread per pixel of the rendered text region.
// Region width  = text_len * 6 - 1   (5 cols + 1 gap per char, no trailing gap)
// Region height = 9                 (1 border + 5 glyph + 1 border + 2 descender)
__global__ void hud_render_kernel(
    cudaSurfaceObject_t surf,
    int32_t fb_width, int32_t fb_height,
    const char* text,
    int32_t text_x, int32_t text_y,
    int32_t text_len,
    uint32_t bg_rgba, uint32_t fg_rgba,
    const uint8_t* font)
{
    int tid = blockIdx.x * blockDim.x + threadIdx.x;
    int total = text_len * 6 - 1;
    if (tid >= total * 9) return;

    int col = tid % total;
    int row = tid / total;

    int char_idx = col / 6;
    int px = text_x + col;
    int py = text_y + row;

    if (px < 0 || px >= fb_width || py < 0 || py >= fb_height) return;
    if (char_idx >= text_len) return;

    uint8_t c = (uint8_t)text[char_idx];
    const uint8_t* glyph = glyph_for(c);

    // Determine on/off:
    // - 1-px border around the 5×7 glyph (row 0, row 8, col 0, col 6): bg
    // - glyph rows 1..7: row 1..5 = glyph rows 0..4 (5 rows);
    //                     row 6..7 = bg (descender area)
    // - glyph cols 1..5: glyph columns 0..4
    bool is_glyph_pixel;
    int glyph_col = col - char_idx * 6 - 1;  // 0..4
    int glyph_row = row - 1;                  // 0..6
    if (glyph_row < 0 || glyph_row > 6 || glyph_col < 0 || glyph_col > 4) {
        is_glyph_pixel = false;  // border
    } else {
        // Bit (4 - glyph_col) in glyph[glyph_row].  But our font
        // convention is bit 4 = leftmost, bit 0 = rightmost (5 bits in a
        // uint8_t, MSB = column 0).  We need to check bit (4 - glyph_col)
        // counting from MSB.  With 7-bit bytes (we only use lower 5 bits),
        // that's: bit position = (1 << (4 - glyph_col)).
        // The font data was authored with bit 4 = leftmost, so glyph[k]
        // encodes the k-th column by MSB-first encoding via `1 << (4 - col)`.
        // We need bit (4 - glyph_col).
        is_glyph_pixel = (glyph[glyph_row] >> (4 - glyph_col)) & 1;
    }

    uchar4 pix;
    if (is_glyph_pixel) {
        pix.x = (fg_rgba >> 0)  & 0xff;
        pix.y = (fg_rgba >> 8)  & 0xff;
        pix.z = (fg_rgba >> 16) & 0xff;
        pix.w = (fg_rgba >> 24) & 0xff;
    } else {
        pix.x = (bg_rgba >> 0)  & 0xff;
        pix.y = (bg_rgba >> 8)  & 0xff;
        pix.z = (bg_rgba >> 16) & 0xff;
        pix.w = (bg_rgba >> 24) & 0xff;
    }

    surf2Dwrite(pix, surf, px * sizeof(uchar4), py);
}

void render(
    cudaArray_t cu_array,
    int32_t fb_width, int32_t fb_height,
    const char* text,
    int32_t text_x, int32_t text_y,
    uint32_t bg_rgba, uint32_t fg_rgba)
{
    if (cu_array == nullptr || text == nullptr) return;

    int32_t text_len = 0;
    while (text[text_len] != '\0' && text_len < 256) text_len++;
    if (text_len == 0) return;

    // Wrap cudaArray in a surface object (cudaCreateSurfaceObject is
    // runtime-API, but accepts driver-API CUarray via the desc).
    cudaResourceDesc desc;
    memset(&desc, 0, sizeof(desc));
    desc.resType = cudaResourceTypeArray;
    desc.res.array.array = cu_array;
    cudaSurfaceObject_t surf = 0;
    cudaError_t create_err = cudaCreateSurfaceObject(&surf, &desc);
    if (create_err != cudaSuccess) {
        throw std::runtime_error(
            std::string("viewer HUD surface creation failed: ")
            + cudaGetErrorString(create_err));
    }

    int32_t total_pixels = (text_len * 6 - 1) * 9;
    int block = 256;
    int grid = (total_pixels + block - 1) / block;
    try {
        hud_render_kernel<<<grid, block, 0, 0>>>(
            surf, fb_width, fb_height,
            text, text_x, text_y, text_len,
            bg_rgba, fg_rgba,
            d_font);

        // Synchronize the stage before tearing down the surface so the
        // surface lifetime stays bounded and explicit.
        swe2d_viewer_interop::check_cuda_stage("viewer HUD", nullptr);

        // Free the surface object now (after the kernel has actually
        // completed — check_cuda_stage above is a barrier).
        cudaError_t derr = cudaDestroySurfaceObject(surf);
        if (derr != cudaSuccess) {
            throw std::runtime_error(
                std::string("viewer HUD surface destroy failed: ")
                + cudaGetErrorString(derr));
        }
    } catch (...) {
        // Best-effort cleanup on any exception path — make sure the
        // surface handle is released even if the stage check or a later
        // destroy already partially failed.
        (void)cudaDestroySurfaceObject(surf);
        throw;
    }
}

